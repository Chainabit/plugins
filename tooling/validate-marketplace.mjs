// Reference marketplace validator — dependency-free, run with plain `node`.
//
//   node tooling/validate-marketplace.mjs                 # check
//   node tooling/validate-marketplace.mjs --write-bundles  # regenerate bundle.json, then check
//
// Checks that this repo is installable as published. A marketplace is only as good as its
// weakest listing: a client resolves an id from `marketplace.json`, clones this repo, reads
// the manifest at the listing's `#<subdirectory>` fragment, and installs what it finds. Any
// break in that chain surfaces to a user as a failed install, so all of it is checked here:
//
//   1. Every plugin folder has a manifest that satisfies the frozen contract.
//   2. Every manifest's declared component files actually exist in its folder.
//   3. `marketplace.json` and the folders on disk describe the same plugins at the same
//      versions, and every listing's `#fragment` names its own folder.
//   4. Every schemaVersion 2 skill DIRECTORY carries a `bundle.json` that matches the files
//      on disk byte for byte.
//
// Rule 4 exists because a server-side installer fetches this repo over raw.githubusercontent.com,
// which serves single files and cannot list a directory. A directory-form skill therefore has to
// declare its own contents, and that declaration is only trustworthy if it can never drift from
// the files beside it — hence: generated by this script, and a hard failure when stale.
//
// Deliberately implements the contract directly rather than validating against the JSON
// Schema. The schema cannot express the rules that break an install:
//
//   - A manifest with an executing component (hooks / install scripts / MCP servers) MUST
//     declare `permissions.shell`. That is the rule that broke this repo before.
//   - A schemaVersion 2 skill directory shipping `scripts/` MUST declare
//     `permissions.execute`, so the consent sheet can say what the user is accepting.
//   - A skill directory's basename MUST equal the `name` in its SKILL.md frontmatter,
//     because the two are separate declarations of the same identity and nothing else
//     catches them drifting.
//
// Those rules live in the installing client's parser, so a schema-only check passes manifests
// the client then refuses. Keep this file in step with the parser, not just the schema.

import { readFileSync, readdirSync, existsSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { basename, dirname, join, relative, sep, posix } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = "chainabit-plugin.json";
const BUNDLE = "bundle.json";
const SOURCE_REPO = "https://github.com/chainabit/plugins.git";

const writeBundles = process.argv.includes("--write-bundles");

// The file types a skill directory may ship. Deliberately narrower than "anything a
// git repo can hold": every entry here is either prose the model reads or a script the
// SANDBOX interpreter runs. Nothing on this list is executable by the host that installs
// the bundle — no .sh, no .bat, no binaries — so an installer never has to decide whether
// a downloaded file is safe to run on its own machine. It isn't; it is only ever copied
// into a container.
const BUNDLE_FILE_EXTENSIONS = new Set([".md", ".py", ".json", ".txt", ".css", ".csv"]);

// 1 is the original contract; 2 adds directory-form skills/providers/execute and
// advisory dependency composition. Both remain installable and composition grants no authority.
const SCHEMA_VERSIONS = new Set([1, 2]);
const SKILL_NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const ID_PATTERN = /^(skill|agent|provider|persona|hook|plugin)-[a-z0-9]+(-[a-z0-9]+)*$/;
const SEMVER =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z-.]+)?(?:\+[0-9A-Za-z-.]+)?$/;
const CATEGORIES = new Set([
  "foundations", "web", "languages", "frameworks", "artifacts", "providers", "personas",
  "research", "code", "security", "productivity", "data", "devops", "infrastructure",
  "databases", "cloud", "testing", "ai", "tooling",
]);
const PHYSICAL_CATEGORIES = new Set([
  "foundations", "web", "languages", "frameworks", "artifacts", "providers", "personas",
  "infrastructure", "databases", "cloud", "devops", "testing", "security", "data", "ai", "tooling",
]);

const problems = [];
const written = [];
const fail = (where, message) => problems.push({ where, message });

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

const isDir = (path) => existsSync(path) && statSync(path).isDirectory();

/** A component path must stay inside its own plugin folder. */
const escapesFolder = (relative) =>
  typeof relative !== "string" ||
  relative.includes("..") ||
  relative.startsWith("/") ||
  relative.startsWith("~");

/**
 * The `name` declared in a SKILL.md's YAML frontmatter, or null when there is no
 * frontmatter block or no name in it. Read with a regex rather than a YAML parser
 * to keep this script dependency-free; the frontmatter contract is one flat block
 * of scalars, so that is enough.
 */
const frontmatterName = (path) => {
  let text;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    return null;
  }
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!block) return null;
  const name = /^name:[ \t]*(\S+)[ \t]*$/m.exec(block[1]);
  return name ? name[1] : null;
};

/**
 * Every file inside a skill directory, as POSIX-relative paths, sorted, with `bundle.json`
 * itself excluded — a manifest cannot describe itself without becoming its own fixed point.
 */
const walkSkillFiles = (root, prefix = "") => {
  const found = [];
  for (const entry of readdirSync(join(root, prefix), { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      found.push(...walkSkillFiles(root, relative));
    } else if (entry.isFile() && relative !== BUNDLE) {
      found.push(relative);
    }
  }
  return found.sort();
};

const fileExtension = (path) => {
  const dot = path.lastIndexOf(".");
  const slash = path.lastIndexOf("/");
  return dot > slash ? path.slice(dot).toLowerCase() : "";
};

/** The bundle document for a skill directory, computed from what is actually on disk. */
const computeBundle = (absolute) => ({
  files: walkSkillFiles(absolute).map((relative) => {
    const bytes = readFileSync(join(absolute, relative));
    return {
      path: relative,
      sha256: createHash("sha256").update(bytes).digest("hex"),
      bytes: bytes.length,
    };
  }),
});

/** Stable serialization, so a regenerated bundle is byte-identical when nothing changed. */
const serializeBundle = (bundle) => `${JSON.stringify(bundle, null, 2)}\n`;

const repoRelative = (absolute) => relative(repoRoot, absolute).split(sep).join("/");

/** Marketplace fragments are repository-relative paths, never arbitrary filesystem paths. */
const isSafePluginPath = (value) => {
  if (typeof value !== "string" || value.length === 0 || value.length > 200) return false;
  if (value.startsWith("/") || value.includes("\\") || value.includes("\0")) return false;
  const parts = value.split("/");
  return parts.every((part) => /^[a-z0-9][a-z0-9._-]{0,63}$/.test(part) && !part.startsWith(".") && !part.includes(".."));
};

/** Discover manifests below canonical category roots, stopping at each plugin root. */
const discoverPluginRoots = (directory) => {
  const roots = [];
  const visit = (current) => {
    if (existsSync(join(current, MANIFEST))) {
      roots.push({ absolute: current, path: repoRelative(current) });
      return;
    }
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      if (entry.isDirectory() && !entry.name.startsWith(".")) visit(join(current, entry.name));
    }
  };
  for (const category of readdirSync(directory, { withFileTypes: true })) {
    if (category.isDirectory() && PHYSICAL_CATEGORIES.has(category.name)) visit(join(directory, category.name));
  }
  return roots.sort((a, b) => a.path.localeCompare(b.path));
};

const pluginRoots = discoverPluginRoots(repoRoot);
const pluginFolders = pluginRoots.map(({ path }) => path);

for (const entry of readdirSync(repoRoot, { withFileTypes: true })) {
  if (entry.isDirectory() && !entry.name.startsWith(".") && !PHYSICAL_CATEGORIES.has(entry.name) && entry.name !== "tooling") {
    if (existsSync(join(repoRoot, entry.name, MANIFEST))) {
      fail(entry.name, "plugin roots must live under a canonical physical category");
    }
  }
}

// --- 1 + 2: every folder's manifest satisfies the contract -----------------------

const manifests = new Map();

for (const plugin of pluginRoots) {
  const folder = plugin.path;
  const manifestPath = join(plugin.absolute, MANIFEST);
  if (!existsSync(manifestPath)) {
    fail(folder, `no ${MANIFEST} — a client that clones this folder cannot install it`);
    continue;
  }

  let m;
  try {
    m = readJson(manifestPath);
  } catch (e) {
    fail(folder, `${MANIFEST} is not parseable: ${e.message}`);
    continue;
  }
  if (manifests.has(m.id)) fail(folder, `duplicate plugin id "${m.id}"; identities must be unique across categories`);
  manifests.set(m.id, { manifest: m, ...plugin });

  if (!SCHEMA_VERSIONS.has(m.schemaVersion)) {
    fail(
      folder,
      `schemaVersion must be one of ${[...SCHEMA_VERSIONS].join(", ")}, found ${m.schemaVersion}`,
    );
  }
  if (!ID_PATTERN.test(m.id ?? "")) {
    fail(folder, `id "${m.id}" is not "<kind>-<slug>"`);
  }
  if (!m.name || m.name.length > 64) {
    fail(folder, `name must be 1–64 characters`);
  }
  if (!SEMVER.test(m.version ?? "")) {
    fail(folder, `version "${m.version}" is not semver`);
  }
  for (const category of m.categories ?? []) {
    if (!CATEGORIES.has(category)) {
      fail(folder, `unknown category "${category}"`);
    }
  }

  const components = m.components ?? {};
  const permissions = m.permissions ?? {};

  // The rule the JSON Schema cannot express — and the one this repo previously broke.
  const executes =
    (components.hooks ?? []).length > 0 ||
    (components.mcpServers ?? []).length > 0 ||
    m.install?.postInstall != null ||
    m.install?.uninstall != null;
  if (executes && permissions.shell !== true) {
    fail(
      folder,
      "declares an executing component (hooks/mcpServers/install) but not " +
        "permissions.shell — the client refuses to install this",
    );
  }

  // Agents and commands are plain file paths, unchanged since schemaVersion 1.
  const filePaths = [...(components.agents ?? []), ...(components.commands ?? [])];
  for (const relative of filePaths) {
    if (escapesFolder(relative)) {
      fail(folder, `component path "${relative}" escapes the plugin folder`);
      continue;
    }
    if (!existsSync(join(plugin.absolute, relative))) {
      fail(folder, `declared component "${relative}" does not exist`);
    }
  }

  // Skills take two forms. A path ending in SKILL.md is the schemaVersion 1 form: one
  // prompt-only document. A directory is the schemaVersion 2 form: SKILL.md plus optional
  // scripts/, references/, assets/. Only the second can carry code, so only the second
  // has anything to consent to.
  const skills = components.skills ?? [];
  let shipsScripts = false;

  for (const relative of skills) {
    if (escapesFolder(relative)) {
      fail(folder, `component path "${relative}" escapes the plugin folder`);
      continue;
    }

    const absolute = join(plugin.absolute, relative);

    if (relative.endsWith("SKILL.md")) {
      if (!existsSync(absolute)) {
        fail(folder, `declared skill "${relative}" does not exist`);
      }
      continue;
    }

    if (m.schemaVersion < 2) {
      fail(
        folder,
        `skill "${relative}" is a directory path, which requires schemaVersion 2 — ` +
          "a version 1 client only understands a path to a SKILL.md file",
      );
    }
    if (!isDir(absolute)) {
      fail(
        folder,
        `declared skill "${relative}" is neither an existing SKILL.md file nor a directory`,
      );
      continue;
    }

    const document = join(absolute, "SKILL.md");
    if (!existsSync(document)) {
      fail(folder, `skill directory "${relative}" has no SKILL.md — there is nothing to load`);
      continue;
    }

    // The directory name and the frontmatter name are two declarations of one identity.
    const directoryName = basename(relative.replace(/\/+$/, ""));
    const declaredName = frontmatterName(document);
    if (declaredName === null) {
      fail(folder, `${relative}/SKILL.md has no "name" in its YAML frontmatter`);
    } else if (!SKILL_NAME_PATTERN.test(declaredName)) {
      fail(
        folder,
        `${relative}/SKILL.md name "${declaredName}" must be lowercase alphanumerics ` +
          "joined by single hyphens",
      );
    } else if (declaredName !== directoryName) {
      fail(
        folder,
        `${relative}/SKILL.md declares name "${declaredName}" but sits in directory ` +
          `"${directoryName}" — the two must match`,
      );
    }

    if (isDir(join(absolute, "scripts"))) {
      shipsScripts = true;
    }

    // --- 4: the directory declares its own contents, accurately ------------------
    //
    // An installer fetching over raw.githubusercontent.com cannot list this directory,
    // so it fetches `bundle.json` and then fetches exactly what the bundle names,
    // verifying each file's sha256. A stale bundle is therefore not cosmetic: it is a
    // failed or silently incomplete install. Regenerate with --write-bundles.
    const bundlePath = join(absolute, BUNDLE);
    const computed = computeBundle(absolute);

    for (const file of computed.files) {
      if (!BUNDLE_FILE_EXTENSIONS.has(fileExtension(file.path))) {
        fail(
          folder,
          `${relative}/${file.path} has a file type a skill bundle may not ship — ` +
            `allowed: ${[...BUNDLE_FILE_EXTENSIONS].join(", ")}`,
        );
      }
    }

    if (writeBundles) {
      writeFileSync(bundlePath, serializeBundle(computed), "utf8");
      written.push(`${folder}/${relative}/${BUNDLE}`);
    }

    if (!existsSync(bundlePath)) {
      fail(
        folder,
        `skill directory "${relative}" has no ${BUNDLE} — an installer cannot list a ` +
          "directory over raw HTTP, so it cannot discover these files. Run " +
          "`node tooling/validate-marketplace.mjs --write-bundles`",
      );
      continue;
    }

    let declared;
    try {
      declared = readJson(bundlePath);
    } catch (e) {
      fail(folder, `${relative}/${BUNDLE} is not parseable: ${e.message}`);
      continue;
    }

    const declaredFiles = Array.isArray(declared?.files) ? declared.files : null;
    if (!declaredFiles) {
      fail(folder, `${relative}/${BUNDLE} has no files[] array`);
      continue;
    }

    const declaredByPath = new Map(declaredFiles.map((f) => [f?.path, f]));
    const computedByPath = new Map(computed.files.map((f) => [f.path, f]));

    for (const path of declaredByPath.keys()) {
      if (!computedByPath.has(path)) {
        fail(folder, `${relative}/${BUNDLE} declares "${path}", which is not on disk`);
      }
    }
    for (const [path, actual] of computedByPath) {
      const entry = declaredByPath.get(path);
      if (!entry) {
        fail(folder, `${relative}/${path} exists but ${BUNDLE} does not declare it`);
        continue;
      }
      if (entry.sha256 !== actual.sha256) {
        fail(
          folder,
          `${relative}/${BUNDLE} declares sha256 ${entry.sha256} for "${path}" but the ` +
            `file hashes to ${actual.sha256} — the bundle is stale`,
        );
      }
      if (entry.bytes !== actual.bytes) {
        fail(
          folder,
          `${relative}/${BUNDLE} declares ${entry.bytes} bytes for "${path}" but the file ` +
            `is ${actual.bytes} bytes`,
        );
      }
    }
  }

  // The second rule the schema cannot express: shipping runnable scripts is a capability
  // the user consents to at install, so it has to be declared.
  if (permissions.execute !== undefined && typeof permissions.execute !== "boolean") {
    fail(folder, `permissions.execute must be a boolean, found ${typeof permissions.execute}`);
  }
  if (permissions.execute === true && m.schemaVersion < 2) {
    fail(folder, "permissions.execute requires schemaVersion 2");
  }
  if (shipsScripts && permissions.execute !== true) {
    fail(
      folder,
      "ships a skill directory containing scripts/ but does not declare " +
        "permissions.execute — the install consent sheet would not disclose it",
    );
  }

  // Providers are AI backend identifiers, not paths, so there is nothing on disk to check.
  const providers = components.providers ?? [];
  if (providers.length > 0 && m.schemaVersion < 2) {
    fail(folder, "components.providers requires schemaVersion 2");
  }
  for (const provider of providers) {
    if (typeof provider !== "string" || provider.trim() === "") {
      fail(folder, `components.providers entry ${JSON.stringify(provider)} must be a non-empty string`);
    }
  }

  const routes = filePaths.length + skills.length + providers.length;
  if (routes === 0 && !executes && m.composition?.role !== "compatibility") {
    fail(folder, "declares no components — it would install but route nothing");
  }
}

// Composition is advisory methodology, never an authority or technology allowlist.
// Validate it here so a selected skill can be resolved without a parallel registry.
for (const [id, entry] of manifests) {
  const folder = entry.path;
  const manifest = entry.manifest;
  const requires = manifest.composition?.requires ?? [];
  if (!Array.isArray(requires)) {
    fail(folder, "composition.requires must be an array of plugin ids");
    continue;
  }
  for (const dependency of requires) {
    if (typeof dependency !== "string" || !ID_PATTERN.test(dependency)) {
      fail(folder, `composition dependency "${dependency}" is not a valid plugin id`);
    } else if (!manifests.has(dependency)) {
      fail(folder, `composition dependency "${dependency}" is not present in this marketplace`);
    }
  }
}

// Dependency cycles make progressive disclosure ambiguous and are always an authoring error.
const visiting = new Set();
const visited = new Set();
const checkCycle = (id, trail = []) => {
  if (visiting.has(id)) {
    fail(id, `composition cycle detected: ${[...trail, id].join(" -> ")}`);
    return;
  }
  if (visited.has(id)) return;
  visiting.add(id);
  for (const dependency of manifests.get(id)?.manifest.composition?.requires ?? []) {
    if (manifests.has(dependency)) checkCycle(dependency, [...trail, id]);
  }
  visiting.delete(id);
  visited.add(id);
};
for (const id of manifests.keys()) checkCycle(id);

// --- 3: the listing and the folders agree ----------------------------------------

let listing;
try {
  listing = readJson(join(repoRoot, "marketplace.json"));
} catch (e) {
  fail("marketplace.json", `not parseable: ${e.message}`);
}

if (listing) {
  const listed = new Map((listing.plugins ?? []).map((p) => [p.id, p]));

  for (const id of listed.keys()) {
    if (!manifests.has(id)) {
      fail("marketplace.json", `lists "${id}" but this repo has no such plugin manifest`);
    }
  }
  for (const [id, plugin] of manifests) {
    if (!listed.has(id)) {
      fail("marketplace.json", `"${id}" exists at ${plugin.path} but is not listed — it is unreachable`);
    }
  }

  for (const [id, entry] of listed) {
    const resolvedPlugin = manifests.get(id);
    const manifest = resolvedPlugin?.manifest;
    if (manifest && entry.version !== manifest.version) {
      fail(
        "marketplace.json",
        `"${id}" is listed at ${entry.version} but its manifest declares ${manifest.version}`,
      );
    }
    const expected = `${SOURCE_REPO}#${resolvedPlugin?.path ?? ""}`;
    if (entry.source !== expected) {
      fail("marketplace.json", `"${id}" source should be ${expected}, found ${entry.source}`);
    }
    const fragment = entry.source?.split("#")[1];
    if (!isSafePluginPath(fragment)) fail("marketplace.json", `"${id}" has an unsafe repository path fragment`);
    if (resolvedPlugin && fragment !== resolvedPlugin.path) fail("marketplace.json", `"${id}" source does not resolve to its manifest path ${resolvedPlugin.path}`);
  }
}

// --- report ----------------------------------------------------------------------

console.log("");
if (written.length > 0) {
  for (const path of written) {
    console.log(`  WROTE ${path}`);
  }
  console.log("");
}
console.log(`Validated ${pluginFolders.length} plugin folder(s) against the frozen contract.`);
console.log("");

if (problems.length === 0) {
  for (const folder of pluginFolders) {
    const plugin = [...manifests.values()].find((candidate) => candidate.path === folder);
    console.log(`  PASS  ${folder}  ${plugin ? `v${plugin.manifest.version}` : ""}`);
  }
  console.log("");
  console.log("marketplace.json is consistent with every plugin folder.");
  console.log("");
  process.exit(0);
}

for (const { where, message } of problems) {
  console.log(`  FAIL  ${where}: ${message}`);
}
console.log("");
console.log(`${problems.length} problem(s) found.`);
console.log("");
process.exit(1);
